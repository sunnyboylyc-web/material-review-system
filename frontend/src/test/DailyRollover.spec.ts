import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, describe, expect, it, vi } from 'vitest'
import App from '../App.vue'
import { SyntheticMockAdapter } from '../adapters/syntheticMockAdapter'

afterEach(() => vi.useRealTimers())
describe('Shanghai daily rollover', () => {
  it('opens the calendar from the whole date input without querying and preserves fallback editing', async () => {
    const adapter = new SyntheticMockAdapter()
    const fetchTop = vi.spyOn(adapter, 'fetchTop')
    const wrapper = mount(App, { props: { adapter } }); await flushPromises()
    const input = wrapper.get('#top-date')
    const picker = vi.fn()
    Object.defineProperty(input.element, 'showPicker', { value: picker, configurable: true })
    const count = fetchTop.mock.calls.length
    await input.trigger('click')
    expect(picker).toHaveBeenCalledTimes(1)
    expect(fetchTop).toHaveBeenCalledTimes(count)
    picker.mockImplementation(() => { throw new Error('unsupported') })
    await input.trigger('click')
    await input.setValue('2026-10-01'); await flushPromises()
    expect(fetchTop).not.toHaveBeenCalled()
    await wrapper.get('.date-form--top').trigger('submit'); await flushPromises()
    expect(fetchTop.mock.lastCall?.[1]).toBe('2026-10-01')
    wrapper.unmount()
  })
  it('retains a manual historical date within the day and resets to yesterday at Shanghai midnight', async () => {
    vi.useFakeTimers({ toFake: ['Date', 'setInterval', 'clearInterval'] })
    vi.setSystemTime(new Date('2026-10-14T15:59:30Z'))
    const adapter = new SyntheticMockAdapter()
    const fetchTop = vi.spyOn(adapter, 'fetchTop')
    const wrapper = mount(App, { props: { adapter } })
    await flushPromises()
    await wrapper.get('#top-date').setValue('2026-10-01')
    window.dispatchEvent(new Event('focus'))
    expect((wrapper.get('#top-date').element as HTMLInputElement).value).toBe('2026-10-01')
    await vi.advanceTimersByTimeAsync(30_000)
    await flushPromises()
    expect((wrapper.get('#top-date').element as HTMLInputElement).value).toBe('2026-10-14')
    expect(fetchTop).not.toHaveBeenCalled()
    wrapper.unmount()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('catches up on wake without waiting for the timer and never resets twice on the same day', async () => {
    vi.useFakeTimers({ toFake: ['Date', 'setInterval', 'clearInterval'] })
    vi.setSystemTime(new Date('2026-10-14T01:00:00Z'))
    const adapter = new SyntheticMockAdapter()
    const fetchTop = vi.spyOn(adapter, 'fetchTop')
    const wrapper = mount(App, { props: { adapter } })
    await flushPromises()
    vi.setSystemTime(new Date('2026-10-16T01:00:00Z'))
    document.dispatchEvent(new Event('visibilitychange'))
    await flushPromises()
    expect(fetchTop).not.toHaveBeenCalled()
    expect((wrapper.get('#top-date').element as HTMLInputElement).value).toBe('2026-10-15')
    await wrapper.get('#top-date').setValue('2026-10-02')
    await flushPromises()
    const count = fetchTop.mock.calls.length
    window.dispatchEvent(new Event('pageshow'))
    await flushPromises()
    expect(fetchTop).toHaveBeenCalledTimes(count)
    expect((wrapper.get('#top-date').element as HTMLInputElement).value).toBe('2026-10-02')
    wrapper.unmount()
  })
})
